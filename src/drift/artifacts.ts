import { readFile } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { parseTestSpec } from "../spec/parser.ts";
import { loadProjectConfig, targetConfigFor, type ProjectConfig } from "../config/project-config.ts";
import { intentTargetFor, type IntentTarget } from "../cli/resolve-case.ts";
import { loadMarkdownCase, type TestCase } from "../intent/case.ts";
import { readSpecFile } from "../store/index.ts";
import { registryFor, resolveTarget } from "../targets/registry.ts";
import { resolveCaseTestPath, resolveTestPathAbs } from "../targets/test-path.ts";
import {
  collectSupportFiles,
  loadTsconfigPaths,
  type TsconfigPaths,
} from "../targets/support-files.ts";
import type { SpecTarget } from "./types.ts";

/**
 * The files that together make up one test case, as a drift audit sees them.
 *
 * A recorded case is two artifacts: the document its author wrote, and the
 * code `ccqa generate` compiled from a recording. The document describes
 * intent in prose; the generated code holds the literal selectors that
 * actually run. They drift independently, so auditing only the document
 * leaves the half that breaks a replay unexamined.
 *
 * A case run live has no second artifact — Claude drives it from the document
 * every time, so the document *is* the test.
 */
export interface SpecArtifacts {
  /**
   * What states the case. Both kinds say the same thing in different
   * vocabularies, and the audit reads the file verbatim either way — the
   * headings a project chose are part of what its author meant.
   */
  intent: { kind: IntentKind; path: string; body: string };
  /** Empty for a live case, and for a recorded case that has not been generated yet. */
  generated: Array<{ path: string; content: string }>;
  /**
   * The import each file was reached through — the entry's `from` is itself.
   * Provenance only: whether a file was read is `generated` versus
   * `unaudited`, and saying it a third time here is a third thing to keep
   * true. Kept so `--dump-inputs` can answer "why is this file here", which
   * is the question behind "did it even reach the audit".
   */
  reached: Array<{ path: string; from: string }>;
  /**
   * Files that belong to this test case but did not fit the byte budget. The
   * audit is told their names: a file it never saw must not read as one it
   * cleared.
   */
  unaudited: string[];
  live: boolean;
  /** Null when the document cannot be parsed. Carried into the report so a drift row
   * reads as the test case it audited, not as its directory path. */
  title: string | null;
}

/**
 * Which document states the case: ccqa's own, or the project's. Derived from
 * the case's own source union so a third document kind cannot be added there
 * without every reader of this being made to answer for it.
 */
export type IntentKind = TestCase["source"]["kind"];

/**
 * Total generated bytes handed to the audit. Generated suites can run long, and
 * the audit's job is to check the strings they name, not to read every line —
 * but a silent cut would let it clear a file it never saw, so what is dropped
 * is always named in `unaudited`.
 */
const MAX_GENERATED_BYTES = 64 * 1024;

/**
 * What a whole sweep shares: the project's config, its import aliases, and the
 * target that owns its own test-case documents. None can change while specs
 * are being audited, and all three would otherwise be re-read per spec.
 */
export interface SpecArtifactsContext {
  config: ProjectConfig;
  tsconfig: TsconfigPaths | null;
  /** Null when the project writes its cases as ccqa `spec.yaml` files. */
  intentTarget: IntentTarget | null;
}

/** Read the sweep-wide inputs once, before the first spec. */
export async function loadSpecArtifactsContext(cwd: string): Promise<SpecArtifactsContext> {
  const [config, tsconfig] = await Promise.all([loadProjectConfig(cwd), loadTsconfigPaths(cwd)]);
  return { config, tsconfig, intentTarget: intentTargetFor(config) };
}

/**
 * Read one case's documents. Throws when the document itself cannot be read —
 * a case enumerated and then gone is an error to report, not an empty audit.
 */
export async function collectCaseArtifacts(
  target: SpecTarget,
  cwd: string,
  ctx: SpecArtifactsContext,
): Promise<SpecArtifacts> {
  return target.caseId === undefined
    ? await collectSpecCase(target.featureName, target.specName, cwd, ctx)
    : await collectIntentCase(target.caseId, cwd, ctx);
}

async function collectSpecCase(
  featureName: string,
  specName: string,
  cwd: string,
  ctx: SpecArtifactsContext,
): Promise<SpecArtifacts> {
  const specYaml = await readSpecFile(featureName, specName, cwd);
  const intent = {
    kind: "spec" as const,
    path: `.ccqa/features/${featureName}/test-cases/${specName}/spec.yaml`,
    body: specYaml,
  };
  const { live, title } = describe(specYaml);
  if (live) return { intent, generated: [], unaudited: [], reached: [], live, title };
  return { intent, ...(await collectSpecGenerated(featureName, specName, specYaml, cwd, ctx)), live, title };
}

/**
 * The generated half alone, for a caller that already holds the spec — the
 * failure classifier, which reads the same code the audit does but brings its
 * own account of what happened.
 */
export async function collectSpecGenerated(
  featureName: string,
  specName: string,
  specYaml: string,
  cwd: string,
  ctx: SpecArtifactsContext,
): Promise<Pick<SpecArtifacts, "generated" | "unaudited" | "reached">> {
  return readGenerated(specTestFile(featureName, specName, specYaml, cwd, ctx.config), cwd, ctx);
}

async function collectIntentCase(
  caseId: string,
  cwd: string,
  ctx: SpecArtifactsContext,
): Promise<SpecArtifacts> {
  // Enumeration and reading share the same target, so this is unreachable
  // unless a caller built the target itself.
  if (!ctx.intentTarget) throw new Error(`${caseId}: no target reads this project's own test cases`);
  const { targetConfig, intent: source } = ctx.intentTarget;
  const testCase = await loadMarkdownCase(caseId, source, cwd);
  const intent = {
    kind: "markdown" as const,
    path: relative(cwd, testCase.source.path),
    body: testCase.source.text,
  };
  const live = testCase.mode === "live";
  if (live) return { intent, generated: [], unaudited: [], reached: [], live, title: testCase.title };
  const plugin = registryFor(ctx.config).get(ctx.intentTarget.id)!;
  const testAbs = resolve(cwd, resolveCaseTestPath(plugin, targetConfig, caseId));
  return { intent, ...(await readGenerated(testAbs, cwd, ctx)), live, title: testCase.title };
}

/**
 * Where this case's generated test lives, project-relative — or null when it
 * has none (a live case, or a document whose target cannot be resolved).
 */
export async function caseTestPath(
  target: SpecTarget,
  cwd: string,
  ctx: SpecArtifactsContext,
): Promise<string | null> {
  if (target.caseId !== undefined) {
    if (!ctx.intentTarget) return null;
    const plugin = registryFor(ctx.config).get(ctx.intentTarget.id)!;
    return resolveCaseTestPath(plugin, ctx.intentTarget.targetConfig, target.caseId);
  }
  const specYaml = await readSpecFile(target.featureName, target.specName, cwd).catch(() => null);
  if (specYaml === null) return null;
  const abs = specTestFile(target.featureName, target.specName, specYaml, cwd, ctx.config);
  return abs === null ? null : relative(cwd, abs);
}

function describe(specYaml: string): { live: boolean; title: string | null } {
  try {
    const spec = parseTestSpec(specYaml);
    return { live: spec.mode === "live", title: spec.title ?? null };
  } catch {
    // An unparsable spec is audited as-is; assuming "not live" only means the
    // generated files are looked for, which is harmless when there are none.
    return { live: false, title: null };
  }
}

/**
 * The code this case runs: the test at the target's `testPath`, then whatever
 * it imports from inside the project. A page object names selectors too, and an
 * audit that stopped at the test file would clear strings it never read.
 */
async function readGenerated(
  testAbs: string | null,
  cwd: string,
  ctx: SpecArtifactsContext,
): Promise<Pick<SpecArtifacts, "generated" | "unaudited" | "reached">> {
  if (testAbs === null) return { generated: [], unaudited: [], reached: [] };
  const files = [
    { abs: testAbs, from: testAbs },
    ...(await collectSupportFiles(testAbs, cwd, { tsconfig: ctx.tsconfig })),
  ];
  // Read together, spend the budget in order: the reads are independent, but
  // which file falls outside the budget must not depend on who finished first.
  const contents = await Promise.all(
    files.map((f) => readFile(f.abs, "utf8").catch(() => null)),
  );

  const generated: Array<{ path: string; content: string }> = [];
  const unaudited: string[] = [];
  const reached: SpecArtifacts["reached"] = [];
  let used = 0;
  for (const [i, content] of contents.entries()) {
    // A path that cannot be read is not part of the case: the walker resolves
    // an import before listing it, so in practice this is the entry of a spec
    // that was never generated — which `unaudited` must not claim exists.
    if (content === null) continue;
    const file = files[i]!;
    const display = relative(cwd, file.abs);
    const from = file.abs === file.from ? "(entry)" : relative(cwd, file.from);
    reached.push({ path: display, from });
    if (used + content.length > MAX_GENERATED_BYTES) {
      unaudited.push(display);
      continue;
    }
    generated.push({ path: display, content });
    used += content.length;
  }
  return { generated, unaudited, reached };
}

/**
 * Where this spec's test lives, resolved through its target. A spec that will
 * not parse, or whose target cannot be resolved, has no test path to derive —
 * the audit then reads the spec alone rather than guessing at a file.
 */
function specTestFile(
  featureName: string,
  specName: string,
  specYaml: string,
  cwd: string,
  config: ProjectConfig,
): string | null {
  try {
    const spec = parseTestSpec(specYaml);
    const target = resolveTarget(spec, config);
    const targetConfig = targetConfigFor(config, target.id);
    return resolveTestPathAbs(target, targetConfig, { featureName, specName }, cwd);
  } catch {
    return null;
  }
}
